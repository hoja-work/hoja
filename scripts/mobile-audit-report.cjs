// Turns the inventory written by scripts/mobile-audit.cjs into docs/mobile-audit.md, one task per screen and per control.
// Usage: node scripts/mobile-audit-report.cjs [inventory.json] [out.md]
const fs = require('node:fs');
const path = require('node:path');

const repo = path.resolve(__dirname, '..');
const input = path.resolve(process.argv[2] || path.join(repo, 'local-e2e/artifacts/mobile-audit/inventory.json'));
const output = path.resolve(process.argv[3] || path.join(repo, 'docs/mobile-audit.md'));
const report = JSON.parse(fs.readFileSync(input, 'utf8'));

// Issue rows repeat per item (ENG-123, Scale issue 45); collapse digits so one row stands for the whole list.
const shape = name => name.replace(/\d+/g, '#');
const KIND = {
  'unlabeled-control': 'no accessible name',
  'touch-target-small': 'touch target under 44px',
  'input-font-under-16px': 'field font under 16px (iOS zooms on focus)',
  'control-overflows-viewport': 'overflows the viewport',
  'control-content-clipped': 'content clipped',
  'controls-overlap': 'overlaps another control',
  'page-horizontal-scroll': 'page scrolls sideways',
};

// Optional click-through results (scripts/mobile-click-through.cjs), keyed by screen and control name.
const functionalPath = path.join(path.dirname(input), 'functional.json');
const functional = new Map();
if (fs.existsSync(functionalPath)) {
  for (const r of JSON.parse(fs.readFileSync(functionalPath, 'utf8'))) functional.set(`${r.screen}|${r.name}`, r);
}
const functionalLabel = { navigated: 'navigates', changed: 'changes the page', 'no-effect': 'no visible effect', error: 'page error', 'click-failed': 'could not be clicked (disabled or covered)', 'not-found': 'not reproduced on reload' };

const widths = [...new Set(report.map(r => r.width))].sort((a, b) => b - a);
const lines = [
  '# Mobile UX audit',
  '',
  'Generated by `scripts/mobile-audit-report.cjs` from `scripts/mobile-audit.cjs` output. Do not edit by hand; rerun the audit.',
  '',
  `Widths audited: ${widths.map(w => `${w}px`).join(', ')}. Each screen is inventoried by DOM and measured in a mobile browser context.`,
  '',
  'A checkbox is ticked when the control has no finding at any audited width. Unticked controls carry the finding as a sub-item.',
  'Functional behaviour (a button does what it says) is not proven by this inventory; see the scripted click-through notes per screen.',
  '',
];

let totalFindings = 0, totalControls = 0;
for (const screen of [...new Set(report.map(r => r.screen))]) {
  const runs = report.filter(r => r.screen === screen);
  const first = runs[0];
  lines.push(`## ${screen}`, '', `Route: \`${first.route}\``, '');
  const findings = runs.flatMap(r => r.issues.map(i => ({ ...i, width: r.width })));
  const controls = new Map();
  for (const run of runs) {
    for (const c of run.controls) {
      const key = `${c.role}|${shape(c.name)}`;
      if (!controls.has(key)) controls.set(key, { role: c.role, name: shape(c.name), count: 0, width: c.w, height: c.h });
      controls.get(key).count++;
    }
  }
  totalControls += [...controls.values()].reduce((n, c) => n + c.count, 0);
  if (findings.length === 0) lines.push('- [x] No findings at any audited width.', '');
  const summary = new Map();
  for (const f of findings) summary.set(f.kind, (summary.get(f.kind) || 0) + 1);
  if (findings.length) {
    lines.push('### Screen-level', '');
    lines.push(`- [ ] Screen has ${findings.length} finding(s): ${[...summary].map(([k, n]) => `${KIND[k] || k} x${n}`).join(', ')}.`);
    lines.push('');
  }
  lines.push('### Controls', '');
  const byControl = new Map();
  for (const f of findings) {
    const m = f.detail.match(/^(\w[\w-]*) "(.*?)"/);
    const key = m ? `${m[1]}|${shape(m[2])}` : null;
    if (key) byControl.set(key, [...(byControl.get(key) || []), f]);
  }
  for (const c of [...controls.values()].sort((a, b) => a.role.localeCompare(b.role) || a.name.localeCompare(b.name))) {
    const key = `${c.role}|${c.name}`;
    const found = byControl.get(key) || [];
    const box = `${c.width}x${c.height}`;
    const label = c.name ? `"${c.name}"` : '(no name)';
    const fn = [...functional.values()].find(r => r.screen === screen && shape(r.name) === c.name);
    const fnNote = fn ? `, click: ${functionalLabel[fn.outcome] || fn.outcome}` : ', click: not run';
    const fnBad = fn && (fn.outcome === 'error' || fn.outcome === 'click-failed');
    lines.push(`- [${found.length || fnBad ? ' ' : 'x'}] ${c.role} ${label}${c.count > 1 ? ` (×${c.count})` : ''}, ${box}px${fnNote}`);
    if (fn && fn.errors && fn.errors.length) lines.push(`  - ${fn.errors[0]}`);
    for (const f of [...new Set(found.map(f => `${KIND[f.kind] || f.kind} at ${f.width}px: ${f.detail}`))]) lines.push(`  - ${f}`);
    totalFindings += found.length;
  }
  lines.push('');
}

lines.splice(6, 0, `Screens: ${new Set(report.map(r => r.screen)).size}. Control instances: ${totalControls}. Findings: ${report.reduce((n, r) => n + r.issues.length, 0)}.`, '');
fs.writeFileSync(output, lines.join('\n'));
console.log(`wrote ${output} (${lines.length} lines)`);
