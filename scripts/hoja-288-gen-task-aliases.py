#!/usr/bin/env python
"""Generate hoja_server/schema_tasks.graphql from schema.graphql (HOJA-288).

Derived, never hand-edited: run this script and commit the output. The mapping
table is the single source of truth for what "task" means, and the compat gate
proves the result is additive.
"""
from __future__ import annotations
import re, sys
from pathlib import Path
from graphql import build_schema, GraphQLObjectType, GraphQLInputObjectType, GraphQLEnumType, Undefined
from graphql.language import print_ast

ROOT = Path(__file__).resolve().parents[1]

# --- the mapping table: single source of truth ---------------------------------
ROOT_FIELDS = {
    "issue": "task", "issues": "tasks", "searchIssues": "searchTasks",
    "issueCreate": "taskCreate", "issueUpdate": "taskUpdate",
    "issueDelete": "taskDelete", "issueArchive": "taskArchive",
    "issueSubscribe": "taskSubscribe", "issueUnsubscribe": "taskUnsubscribe",
    "myIssueActivity": "myTaskActivity",
    "issueLabels": "taskLabels", "issueLabelCreate": "taskLabelCreate",
    "issueLabelUpdate": "taskLabelUpdate", "issueLabelDelete": "taskLabelDelete",
    "issueLabelSettings": "taskLabelSettings",
}
TYPE_MAP = {
    "Issue": "Task", "IssueConnection": "TaskConnection", "IssuePayload": "TaskPayload",
    "IssueActivity": "TaskActivity", "IssueActivityConnection": "TaskActivityConnection",
    "MyIssueActivity": "MyTaskActivity", "MyIssueActivityConnection": "MyTaskActivityConnection",
    "IssueFilter": "TaskFilter", "IssueCreateInput": "TaskCreateInput",
    "IssueUpdateInput": "TaskUpdateInput", "IssueParentFilter": "TaskParentFilter",
}
# Field names that themselves carry the product word. The containing type is being
# aliased, so the member is renamed too and rebound to the original resolver.
TYPE_FIELD_RENAMES = {"MyTaskActivity": {"issue": "task"}, "TaskPayload": {"issue": "task"}}
DEPRECATION = "Use the task* equivalent; kept as a wire-compatible alias."

def remap(type_str: str) -> str:
    for old, new in sorted(TYPE_MAP.items(), key=lambda kv: -len(kv[0])):
        type_str = re.sub(rf"\b{re.escape(old)}\b", new, type_str)
    return type_str

def render_default(node) -> str:
    """Defaults are only on the AST node in graphql-core 3.3; print the literal verbatim."""
    dv = getattr(node, "default_value", None) if node is not None else None
    if dv is None:
        return ""
    return " = " + print_ast(dv)


def render_args(field) -> str:
    if not field.args:
        return ""
    parts = [f"{n}: {remap(str(a.type))}{render_default(a.ast_node)}" for n, a in field.args.items()]
    return "(" + ", ".join(parts) + ")"

def main() -> int:
    schema = build_schema((ROOT / "hoja_server/schema.graphql").read_text())
    out: list[str] = [
        "# GENERATED by scripts/hoja-288-gen-task-aliases.py — do not edit by hand.",
        "# The task* surface mirrors the issue* surface; issue* stays as a deprecated alias.",
        "",
    ]
    # 1. type aliases (objects and inputs), fields remapped where they reference Issue*
    for old, new in TYPE_MAP.items():
        t = schema.type_map.get(old)
        if t is None:
            continue
        if isinstance(t, GraphQLObjectType):
            out.append(f"type {new} {{")
            renames = TYPE_FIELD_RENAMES.get(new, {})
            for fname, f in t.fields.items():
                out.append(f"  {renames.get(fname, fname)}{render_args(f)}: {remap(str(f.type))}")
            out.append("}")
        elif isinstance(t, GraphQLInputObjectType):
            out.append(f"input {new} {{")
            for fname, f in t.fields.items():
                out.append(f"  {fname}: {remap(str(f.type))}{render_default(f.ast_node)}")
            out.append("}")
        out.append("")
    # 2. root field aliases via extend
    q, m = schema.query_type, schema.mutation_type
    qn, mn = [], []
    for old, new in ROOT_FIELDS.items():
        for root, bucket in ((q, qn), (m, mn)):
            f = (root.fields or {}).get(old) if root else None
            if f:
                bucket.append(f"  {new}{render_args(f)}: {remap(str(f.type))}")
    if qn:
        out.append("extend type Query {"); out.extend(qn); out.append("}"); out.append("")
    if mn:
        out.append("extend type Mutation {"); out.extend(mn); out.append("}"); out.append("")

    dest = ROOT / "hoja_server/schema_tasks.graphql"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest.relative_to(ROOT)} ({len(out)} lines)")
    print(f"  type aliases: {len(TYPE_MAP)}   query fields: {len(qn)}   mutation fields: {len(mn)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
